static void button_signal_handler_task(void* argument) {
  (void)argument;

  for (;;) {
    if (xSemaphoreTake(button_signal_semaphore_handle, portMAX_DELAY) ==
        pdTRUE) {
      (void)xSemaphoreGive(sibling_send_semaphore_handle);
    }
  }
}

static void sibling_receive_handler_task(void* argument) {
  uint8_t is_led_on = 0U;
  (void)argument;

  for (;;) {
    if (xSemaphoreTake(sibling_receive_semaphore_handle, portMAX_DELAY) ==
        pdTRUE) {
      if (is_led_on != 0U) {
        led_off(led);
        is_led_on = 0U;
      } else {
        led_on(led);
        is_led_on = 1U;
      }
    }
  }
}

